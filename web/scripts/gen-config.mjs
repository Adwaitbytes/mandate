// Juror facts come from the worker code itself so the site never drifts from what the jurors call.
function readModel(file, constant) {
  const source = readFileSync(join(repo, "workers", "src", "providers", file), "utf8");
  const match = new RegExp(`export const ${constant} = "([^"]+)";`).exec(source);
  if (!match) throw new Error(`Could not find ${constant} in workers/src/providers/${file}`);
  return match[1];
}
