// Generates src/generated/abi.ts and src/generated/deployments.ts from the Foundry project next door.
// Run after `forge build` and after every deployment: `pnpm gen`. The output is committed so the site builds
// without the contracts toolchain (Vercel builds web/ alone).
//
// Sources, in order of trust:
//   contracts/out/<Name>.sol/<Name>.json                 ABIs
//   contracts/deployments/<chainId>.env                   addresses (append-only; the last line for a key wins)
//   contracts/broadcast/DeployMandate.s.sol/<chainId>/run-latest.json   deployment blocks, when present
import { existsSync, readdirSync, readFileSync, writeFileSync } from "node:fs";
import { dirname, join } from "node:path";
import { fileURLToPath } from "node:url";
import { keccak256, toBytes } from "viem";

const here = dirname(fileURLToPath(import.meta.url));
const repo = join(here, "..", "..");
const contracts = join(repo, "contracts");
const outDir = join(here, "..", "src", "generated");

const ABIS = ["MandateReactive", "Docket", "Delegate", "DemoGovernor", "DemoVotesToken"];
/** Live chains only. 31337 is the local anvil run and never reaches the site. */
const CHAINS = { lasna: 5318007, baseSepolia: 84532, unichainSepolia: 1301 };
const ADDRESS = /^0x[0-9a-fA-F]{40}$/;

function readAbi(name) {
  const path = join(contracts, "out", `${name}.sol`, `${name}.json`);
  if (!existsSync(path)) throw new Error(`Missing ${path}. Run forge build in contracts/ first.`);
  return JSON.parse(readFileSync(path, "utf8")).abi;
}

function readEnv(chainId) {
  const path = join(contracts, "deployments", `${chainId}.env`);
  if (!existsSync(path)) return {};
  const values = {};
  for (const line of readFileSync(path, "utf8").split("\n")) {
    const match = /^([A-Z_]+)=(\S+)$/.exec(line.trim());
    if (!match) continue;
    const [, key, value] = match;
    if (!ADDRESS.test(value)) throw new Error(`${path}: ${key} is not an address: ${value}`);
    values[key] = value;
  }
  return values;
}

/** Lowest block that created any contract in the latest broadcast for this chain, or null. */
function readStartBlock(chainId) {
  const root = join(contracts, "broadcast");
  if (!existsSync(root)) return null;
  let best = null;
  for (const script of readdirSync(root)) {
    const path = join(root, script, String(chainId), "run-latest.json");
    if (!existsSync(path)) continue;
    const run = JSON.parse(readFileSync(path, "utf8"));
    for (const receipt of run.receipts ?? []) {
      const block = Number.parseInt(receipt.blockNumber, 16);
      if (Number.isSafeInteger(block) && (best === null || block < best)) best = block;
    }
  }
  return best;
}

const abiSource = [
  "// Generated by scripts/gen-config.mjs from contracts/out. Do not edit by hand.",
  ...ABIS.map(
    (name) =>
      `export const ${name[0].toLowerCase()}${name.slice(1)}Abi = ${JSON.stringify(readAbi(name))} as const;`,
  ),
  "",
].join("\n\n");

