const ADDRESS = /^0x[0-9a-fA-F]{40}$/;

function readAbi(name) {
  const path = join(contracts, "out", `${name}.sol`, `${name}.json`);
  if (!existsSync(path)) throw new Error(`Missing ${path}. Run forge build in contracts/ first.`);
  return JSON.parse(readFileSync(path, "utf8")).abi;
}

function readEnv(chainId) {
  const path = join(contracts, "deployments", `${chainId}.env`);
  if (!existsSync(path)) return {};
  const values = {};
  for (const line of readFileSync(path, "utf8").split("\n")) {
    const match = /^([A-Z_]+)=(\S+)$/.exec(line.trim());
    if (!match) continue;
    const [, key, value] = match;
    if (!ADDRESS.test(value)) throw new Error(`${path}: ${key} is not an address: ${value}`);
    values[key] = value;
  }
  return values;
}

/** Lowest block that created any contract in the latest broadcast for this chain, or null. */
function readStartBlock(chainId) {
  const root = join(contracts, "broadcast");
  if (!existsSync(root)) return null;
  let best = null;
  for (const script of readdirSync(root)) {
    const path = join(root, script, String(chainId), "run-latest.json");
    if (!existsSync(path)) continue;
    const run = JSON.parse(readFileSync(path, "utf8"));
    for (const receipt of run.receipts ?? []) {
      const block = Number.parseInt(receipt.blockNumber, 16);
      if (Number.isSafeInteger(block) && (best === null || block < best)) best = block;
    }
  }
  return best;
}

