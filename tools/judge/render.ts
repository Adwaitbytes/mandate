function evalLines(s: Summary): string {
  const card = s.eval.find((c) => c.card.endsWith("MODEL_CARD.md"));
  if (card === undefined) return "The evaluation card is missing.";
  const rows = Object.entries(card.agreement).map(([m, a]) => {
    const d = card.decisions[m] ?? {};
    return [
      `\`${m}\``,
      String(a.n),
      pct(a.allThree, a.n),
      pct(a.atLeastTwo, a.n),
      `${d.for ?? 0} for, ${d.against ?? 0} against, ${d.abstain ?? 0} abstain, ${d["held-split"] ?? 0} held split, ${d["held-injection"] ?? 0} held by a flag`,
    ];
  });
  return table(
    ["Mandate", "Proposals", "All three jurors agree", "At least two agree", "Quorum decision"],
    rows,
  );
}

/** "j1:against@8500:INJ j2:for@9000" -> "juror 1 against at 8500 bps with an injection flag, juror 2 for at 9000 bps" */
function verdictProse(cell: string): string {
  return cell
    .split(" ")
    .filter(Boolean)
    .sort()
    .map((p) => {
      const m = /^j(\d):(\w+)@(\d+)(:INJ)?$/.exec(p);
      return m ? `juror ${m[1]} ${m[2]} at ${m[3]} bps${m[4] ? " with an injection flag" : ""}` : p;
    })
    .join(", ");
}

/** What the evaluation says the mandate does, and the weak result next to it. */
function mandateEffect(s: Summary): string {
  const card = s.eval.find((c) => c.card.endsWith("MODEL_CARD.md"));
  if (card === undefined) return "";
  const d = card.decisionDiffers;
  const matches = Object.entries(card.outcomeMatch)
    .map(([m, o]) => `${pct(o.matches, o.decided)} of decided cases under \`${m}\``)
    .join(" and ");
  return `The mandate changes the vote: the quorum decision differs between the two mandates on ${pct(d.num, d.den)} of proposals. Agreement with how the DAO actually voted is ${matches}; a mandate is a personal policy, so that is how often this voter sides with the majority, not accuracy. The card lists where the jurors disagree and why.`;
}

