const short = (h: string) => `${h.slice(0, 10)}…${h.slice(-4)}`;
const tx = (chain: number, h: string) =>
  h ? `[\`${short(h)}\`](${EXPLORER_TX[chain as ChainId]}${h})` : "none";
const addr = (chain: number, a: string) => `[\`${a}\`](${EXPLORER_ADDRESS[chain as ChainId]}${a})`;
const secs = (ms: number) =>
  `${(ms / 1000).toLocaleString("en-US", { minimumFractionDigits: 1, maximumFractionDigits: 1 })} s`;
const chainLabel = (c: number) => CHAIN_NAME[c as ChainId];
const contractName = (n: string) =>
  n.replace(/\s*\((?:owner|linked|delay|timestamp|block)[^)]*\)/g, "").replace(/, same token$/, "");

function table(head: string[], rows: string[][]): string {
  return [
    `| ${head.join(" | ")} |`,
    `|${head.map(() => "---").join("|")}|`,
    ...rows.map((r) => `| ${r.join(" | ")} |`),
  ].join("\n");
}

function caseRow(s: Summary, label: string): CaseSummary {
  const c = s.run.perCase.find((x) => x.label === label);
  if (c === undefined) throw new Error(`no case ${label} in summary.json`);
  return c;
}

/** Step label in prose, from the stats.py step and clock names. */
function stepLabel(step: string, clock: string): string {
  const names: Record<string, string> = {
    "proposal -> case open on Docket": "Proposal to case open on the Docket",
    "case open -> first verdict": "Case open to first verdict",
    "case open -> third verdict (quorum 3)": "Case open to third verdict (quorum 3)",
    "third verdict -> window start on Lasna": "Third verdict to veto window start on Lasna",
    "window start -> window end": "Veto window",
    "window end -> cast on governor": "Window end to vote cast on the governor",
    "proposal -> cast (whole loop)": "Proposal to vote cast, whole loop",
    "third verdict -> owner veto tx": "Third verdict to owner veto",
  };
  const clocks: Record<string, string> = {
    "Base ms (200 ms)": "Base, ms stamps",
    "raw: Unichain s vs Base ms (+-1 s)": "Unichain s to Base ms, plus or minus 1 s",
    "Base ms": "Base, ms stamps",
    "raw: Base ms vs Lasna s (Lasna stamps run early)": "Base ms to Lasna s, Lasna stamps run early",
    "Lasna s (config 300 s)": "Lasna s, configured 300 s",
    "raw: Lasna s vs governor clock": "Lasna s to governor chain",
    "same clock, Base ms": "Base, same clock",
    "same clock, Unichain s": "Unichain, same clock",
    "Base ms (human/script latency)": "Base, owner by hand",
  };
  return `${names[step] ?? step} | ${clocks[clock] ?? clock}`;
}

function timingTable(s: Summary): string {
  return table(
    ["Step", "Clock", "n", "p50", "p90", "min", "max"],
    s.run.timing.map((t) => [
      ...stepLabel(t.step, t.clock).split(" | "),
      String(t.n),
      secs(t.p50),
      secs(t.p90),
      secs(t.min),
      secs(t.max),
    ]),
  );
}

function step(s: Summary, name: string, clock: string) {
  const t = s.run.timing.find((x) => x.step === name && x.clock === clock);
  if (t === undefined) throw new Error(`no timing step ${name} / ${clock}`);
  return t;
}

/** Every hop of one loop with its link and its time from the proposal (each chain's own clock). */
function loopTable(s: Summary, label: string): string {
  const c = caseRow(s, label);
  const h = s.hops[c.caseId];
  if (h === undefined) throw new Error(`no hops for ${label}`);
  const t0 = c.stamps.proposal ?? 0;
  const at = (ms: number | null | undefined) => (ms ? `${ms >= t0 ? "+" : ""}${secs(ms - t0)}` : "");
  const st = c.stamps;
  const models = Object.fromEntries(c.models.split(" ").map((p) => [p.slice(0, 2), p.slice(3)]));
  const rows: string[][] = [
    ["Proposal filed (`ProposalCreated`)", chainLabel(c.chainId), tx(c.chainId, c.proposalTx), "0"],
    [
      "Reactive contract opens the case (`CaseCreated`, requests `openCase`)",
      "Lasna",
      tx(LASNA, h.caseCreated),
      at(st.caseCreated),
    ],
    [
      "Callback: case opened on the Docket (`CaseOpened`)",
      "Base Sepolia",
      tx(84532, c.docketOpenTx),
      at(st.docketOpen),
    ],
    ["Acknowledgement read back (case Open)", "Lasna", tx(LASNA, h.openAck), ""],
  ];
  for (const j of ["j1", "j2", "j3"]) {
    const v = c.verdictTxs[j];
    if (v)
      rows.push([
        `Verdict, juror ${j.slice(1)} (\`${models[j] ?? "?"}\`)`,
        "Base Sepolia",
        tx(84532, v),
        at(st[`verdict_${j}`]),
      ]);
  }
  if (c.overrideTx) rows.push(["Owner override (`Overridden`)", "Base Sepolia", tx(84532, c.overrideTx), ""]);
  if (h.windowStarted)
    rows.push([
      "Tally decides, veto window starts (`WindowStarted`)",
      "Lasna",
      tx(LASNA, h.windowStarted),
      at(st.windowStarted),
    ]);
  if (h.castDeferred)
    rows.push([
      "Window over before voting opened (`CastDeferred`, case Waiting)",
      "Lasna",
      tx(LASNA, h.castDeferred),
      "",
    ]);
  if (h.castRequested)
    rows.push([
      "Cron tick requests the vote (`CastRequested`)",
      "Lasna",
      tx(LASNA, h.castRequested),
      at(st.castRequested),
    ]);
  if (c.castTx)
    rows.push([
      "Callback: Delegate casts the vote (`Cast`)",
      chainLabel(c.chainId),
      tx(c.chainId, c.castTx),
      at(st.cast),
    ]);
  if (h.castAck)
    rows.push(["Acknowledgement read back (case Cast)", "Lasna", tx(LASNA, h.castAck), at(st.castAck)]);
  return table(["Hop", "Chain", "Transaction", "Time from proposal"], rows);
}

