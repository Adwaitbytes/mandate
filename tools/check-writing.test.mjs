// Run with: node --test tools/
import assert from "node:assert/strict";
import { test } from "node:test";
import { checkSource, extractTsText } from "./check-writing.mjs";

const rules = (file, src) => checkSource(file, src).map((v) => `${v.line}:${v.message}`);

test("JSX text, attribute strings and literals are checked; code and comments are not", () => {
  const src = [
    "// an unlock comment — not user-facing",
    "import { unlock } from './pool';",
    "export function Hero() {",
    "  const n = items.length > 2 ? 1 : 0;",
    "  unlock(n);",
    '  return <section aria-label="A seamless loop">',
    "    <h1>One loop — three chains</h1>",
    "    {n > 0 && <p>{`Robust ${n} times`}</p>}",
    "    <Badge label={'ok \u{1F680}'} />",
    "  </section>;",
    "}",
  ].join("\n");
  assert.deepEqual(rules("web/src/app/page.tsx", src), [
    "6:banned word: seamless",
    "7:em dash",
    "8:banned word: robust",
    "9:emoji",
  ]);
});

test("generics, comparisons and regex literals do not open JSX", () => {
  const src = [
    "const a = useState<string>('x');",
    "if (a < b && c > d) go();",
    "const re = /<div>—/g;",
    "const s = 'after';",
  ].join("\n");
  assert.deepEqual(
    extractTsText(src, true).map((s) => s.text),
    ["x", "after"],
  );
});

test("markdown skips code, link targets and URLs but checks prose", () => {
  const src = [
    "# Title",
    "Call `manager.unlock()` first.",
    "```solidity",
    "manager.unlock(data); // —",
    "```",
    "See [the docs](https://example.com/robust-guide).",
    "This is not just fast but cheap.",
    "Ranges like 10–20 are fine; Base – Lasna is not.",
    "We leverage the system contract. Leverage ratio is a noun.",
    "<!-- writing-check-ignore-next-line: quoting the banned list -->",
    "Banned: revolutionary.",
  ].join("\n");
  assert.deepEqual(rules("README.md", src), [
    '7:banned construction: "not just X but Y"',
    "8:en dash used as punctuation",
    "9:banned: leverage as a verb",
  ]);
});

test("generated files are skipped", () => {
  assert.deepEqual(rules("web/src/lib/x.ts", "// Generated by scripts/gen.mjs. Do not edit.\nexport const a = 'robust';"), []);
});
